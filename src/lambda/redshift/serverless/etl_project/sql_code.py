create_scd1_sp_sql="""
    CREATE OR REPLACE PROCEDURE scd1_upsert(
        )
        LANGUAGE plpgsql
        AS $$
    
        BEGIN

        -- by etl design no duplicates on natural key in staging table

        -- using natural key to derive surrogateKey for fact

        DROP TABLE IF EXISTS #keychange;

        CREATE TEMP TABLE #keychange AS 
            select 
                o.order_id, 
                coalesce(c.customer_sk,-99) as customer_sk,
                o.order_status,
                o.order_amount,
                o.order_ts,
                o.updated_ts,
                o.extract_date
            from  orders_staging o 
            left join customers c
            on(o.customer_id=c.customer_id)
            and(c.is_latest = true);

        
        MERGE INTO orders
                USING #keychange
                ON orders.order_id = #keychange.order_id
                WHEN MATCHED THEN 
                    UPDATE SET 
                    customer_sk = #keychange.customer_sk,
                    order_status = #keychange.order_status,
                    order_amount= #keychange.order_amount,
                    updated_ts= #keychange.updated_ts,
                    extract_date= #keychange.extract_date,
                    is_updated=true

                WHEN NOT MATCHED THEN 
        
                    INSERT (
                        order_id ,    
                        customer_sk   ,
                        order_status  ,
                        order_amount  ,
                        order_ts      ,
                        updated_ts   ,
                        extract_date  ,
                        is_updated  
                    )

                    VALUES (
                    #keychange.order_id, 
                    #keychange.customer_sk,
                    #keychange.order_status,
                    #keychange.order_amount,
                    #keychange.order_ts,
                    #keychange.updated_ts,
                    #keychange.extract_date,
                    false
                    );

        DROP TABLE IF EXISTS #keychange;
        END;
        $$;

"""

create_scd2_sql="""
             CREATE OR REPLACE PROCEDURE scd2(
    )
    LANGUAGE plpgsql
    AS $$
    DECLARE

        curr_time TIMESTAMPTZ := GETDATE();
        is_first_load BOOLEAN :=FALSE;

    BEGIN

    -- remember as per ETL design , we are sure that natural key is unique in stg

    -- merge (for matching rows, we decomission old rows , and insert new rows for non-matching records)

    MERGE INTO customers
                USING customers_staging
                ON customers.customer_id = customers_staging.customer_id
                AND (customers.is_latest=true) --this should be only 1, rest all should be false
                WHEN MATCHED THEN 
                    UPDATE SET 
                    is_latest = false,
                    end_timestamp = curr_time
                WHEN NOT MATCHED THEN 
        
                    INSERT (customer_id,
                    customer_name,
                    updated_ts,
                    extract_date,
                    start_timestamp,
                    end_timestamp,
                    is_latest)

                    VALUES (customers_staging.customer_id, 
                    customers_staging.customer_name,
                    customers_staging.updated_ts,
                    customers_staging.extract_date,
                    curr_time,
                    '2099-12-31 23:59:59'::TIMESTAMP,
                    true
                    );


    -- for matching records, we insert a new row

    DROP TABLE IF EXISTS #joinedSet;
    DROP TABLE IF EXISTS #newVersion;

    CREATE TEMP TABLE #joinedSet AS 
    SELECT cs.*,
    row_number() over(partition by cs.customer_id order by ct.customer_id desc) rn   -- need 1 record from staging
    from customers_staging cs
    join customers ct
    on(cs.customer_id=ct.customer_id)     -- join on natural key
    and(ct.is_latest=false) ;--we have already inserted new records with true- so using this to capture only old matched recs, otherwise new inserts will also get joined and duplicated


    -- this is for matching records- where we create a new row with the new version
    CREATE TEMP TABLE #newVersion AS 
    select 
    js.customer_id,
    js.customer_name,
    js.updated_ts,
    js.extract_date,
    curr_time as start_timestamp,
    '2099-12-31 23:59:59'::TIMESTAMP as end_timestamp,
    true as is_latest
    from #joinedSet js
    where rn=1; -- we need only 1 record from staging, since we join , we can get multiple rows but keep only 1


  INSERT INTO customers (
    customer_id,
    customer_name,
    updated_ts,
    extract_date,
    start_timestamp,
    end_timestamp,
    is_latest
)
SELECT 
    customer_id,
    customer_name,
    updated_ts,
    extract_date,
    start_timestamp,
    end_timestamp,
    is_latest 
FROM #newVersion;

    DROP TABLE #joinedSet;
    DROP TABLE #newVersion;

    -- default row for dims
    SELECT NOT EXISTS (
    SELECT 1 FROM customers WHERE customer_sk = -99
) INTO is_first_load; --    if it does not exists this makes variable TRUE
    
    IF is_first_load = true THEN
        INSERT INTO customers(    
                    customer_sk,
                    customer_id,
                    customer_name,
                    updated_ts,
                    extract_date,
                    start_timestamp,
                    end_timestamp,
                    is_latest)

                    VALUES (
                        -99,
                        'unknown',
                        'unknown',
                        '1900-12-31 23:59:59'::TIMESTAMP,
                        '1900-12-31'::DATE,
                        '1900-12-31 23:59:59'::TIMESTAMP,
                        '2099-12-31 23:59:59'::TIMESTAMP,
                        true
                    );
    END IF;

    END;
    $$;
    """
